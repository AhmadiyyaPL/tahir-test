// Polish plural: 1 zadanie · 2–4 zadania · 5+ zadań (12–14 are always "many").
function plp(n, one, few, many) {
  if (n === 1) return one;
  const d = n % 10, h = n % 100;
  return d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
}
const enp = (n, one, many) => (n === 1 ? one : many);

